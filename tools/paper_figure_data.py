"""Write the small data tables the paper's pgfplots charts read.

    python3 tools/paper_figure_data.py   # -> paper/figures/data/*.dat

Standard library only. Every table is computed from results/ so the charts in
paper/ never hold hand-typed numbers:
  rd_<material>_<fmt>.dat   FLIP vs bits per texel   results/milestone/results.csv (texel loss)
  speed.dat                 ms per 1080p frame       results/decoder/v2_baselines.json
  rounding.dat              mean FLIP change, %      results/rounding/runs.csv (per-model ratio, then mean)
"""

import collections
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "paper" / "figures" / "data"

SPEED_LABELS = {  # data key -> (row label, group: 0 PyTorch, 1 ours FP16, 2 ours FP4)
    "pytorch eager fp32 (CUDA cores)": ("PyTorch, fp32", 0),
    "pytorch eager fp32, TF32 Tensor Cores": ("PyTorch, fp32 (TF32)", 0),
    "pytorch eager fp16 (Tensor Cores)": ("PyTorch, fp16", 0),
    "pytorch compiled fp32": ("PyTorch compiled, fp32", 0),
    "pytorch compiled fp16 (Tensor Cores)": ("PyTorch compiled, fp16", 0),
    "CUDA FP16-unpack (ours)": ("Ours: FP16-unpack", 1),
    "CUDA FP4-direct (ours)": ("Ours: FP4-direct", 2),
}


def write(name, header, rows, source):
    with open(OUT / name, "w") as f:
        f.write(f"% generated by tools/paper_figure_data.py from {source}\n")
        f.write(" ".join(header) + "\n")
        for r in rows:
            f.write(" ".join(str(x) for x in r) + "\n")


def rd():
    src = "results/milestone/results.csv"
    pts = collections.defaultdict(list)
    for r in csv.DictReader(open(ROOT / src)):
        if r["loss_name"] == "texel":
            pts[(r["material"], r["fmt"])].append((float(r["bpp_total"]), float(r["flip"])))
    for (mat, fmt), p in pts.items():
        write(f"rd_{mat}_{fmt}.dat", ["bpt", "flip"], [(f"{b:.4f}", f"{v:.5f}") for b, v in sorted(p)], src)


def speed():
    src = "results/decoder/v2_baselines.json"
    ms = json.loads((ROOT / src).read_text())["ms"]
    fp4 = ms["CUDA FP4-direct (ours)"]
    keys = sorted(ms, key=lambda k: ms[k], reverse=True)  # slowest first = top row
    rows = []
    for i, k in enumerate(keys):
        label, group = SPEED_LABELS[k]
        r = ms[k] / fp4
        mslabel = f"{ms[k]:.3f}" if ms[k] < 1 else f"{ms[k]:.1f}"
        rows.append((i, f"{ms[k]:.4f}", mslabel, group, f"{r:.2f}" if r < 10 else f"{r:.1f}", "{" + label + "}"))
    write("speed.dat", ["y", "ms", "mslabel", "group", "ratio", "label"], rows, src)


def rounding():
    src = "results/rounding/runs.csv"
    runs = collections.defaultdict(dict)
    for r in csv.DictReader(open(ROOT / src)):
        runs[(r["fmt"], r["train_loss"], r["material"], r["seed"])][r["arm"]] = r
    rows = []
    for i, (fmt, tl) in enumerate([("mxfp4", "shading"), ("mxfp4", "texel"), ("nvfp4", "shading"), ("nvfp4", "texel")]):
        ms = [m for k, m in runs.items() if k[:2] == (fmt, tl) and {"nearest", "texel", "shading"} <= m.keys()]
        def rel(metric, arm):
            return sum(100 * (float(m[arm][metric]) / float(m["nearest"][metric]) - 1) for m in ms) / len(ms)
        rows.append((i, f"{fmt.upper()}/{tl}", len(ms),
                     f"{rel('flip', 'texel'):.2f}", f"{rel('flip', 'shading'):.2f}",
                     f"{rel('flip_unseen', 'texel'):.2f}", f"{rel('flip_unseen', 'shading'):.2f}"))
    write("rounding.dat", ["x", "group", "n", "texel_test", "shading_test", "texel_unseen", "shading_unseen"], rows, src)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    rd()
    speed()
    rounding()
    print("wrote", sorted(p.name for p in OUT.iterdir()))
